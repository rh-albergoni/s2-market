const MES=new Date().getFullYear()+"-"+String(new Date().getMonth()+1).padStart(2,"0");

console.log("1. Duas pessoas no mercado ao mesmo tempo");
const srv=servidor();
const A=celular(srv,{nome:"Ana",hash:"#/ida/i1"}), B=celular(srv,{nome:"Leo",hash:"#/ida/i1"});
await wait(400);
ok(A.erros.length===0&&B.erros.length===0,"sem erros ao abrir "+A.erros.concat(B.erros).join(" | "));
ok(A.txt(".idahead h1")==="Dia 1 · Compra grande","título da ida: "+A.txt(".idahead h1"));
ok(A.txt(`.it[data-k="i1:frango"] .it-q`)==="6 kg","frango 6 kg para 3 pessoas");
ok(A.qa(".it[data-k]").length>=45,"lista com "+A.qa(".it[data-k]").length+" itens");
A.tap("i1:banana"); B.tap("i1:frango"); A.tap("i1:arroz");
ok(A.item("i1:banana").classList.contains("s-ok"),"marcação aparece na hora (otimista)");
ok(A.item("i1:banana").classList.contains("saindo"),"item marcado fica visível um instante no filtro Faltam");
await wait(400); await A.sync(); await B.sync(); await A.sync();
const sa=A.ev("JSON.stringify(S.meses)"), sb=B.ev("JSON.stringify(S.meses)");
ok(sa===sb,"os dois aparelhos ficaram iguais");
const it=JSON.parse(sa)[MES].itens;
ok(it["i1:banana"]?.s==="ok"&&it["i1:frango"]?.s==="ok"&&it["i1:arroz"]?.s==="ok","três marcações de duas pessoas preservadas");
ok(it["i1:frango"].por==="Leo","registra quem marcou");
A.click(`[data-act="filtro"][data-f="todos"]`);
ok(A.txt(`.it[data-k="i1:frango"] .it-tag`)==="Leo","A vê a etiqueta 'Leo' no item que Leo pegou");
ok(/com Leo/.test(A.txt(".idahead")||""),"A vê que Leo está na mesma lista: "+(A.q(".pres")?.textContent||"nada"));
await wait(2800);
B.click(`[data-act="filtro"][data-f="faltam"]`);
ok(!B.item("i1:banana"),"no filtro Faltam, B não vê a banana que A pegou");

console.log("2. Mesmo item tocado pelos dois quase juntos");
A.tap("i1:cafe"); B.click(`[data-act="filtro"][data-f="todos"]`); B.tap("i1:cafe");
await wait(400); await A.sync(); await B.sync(); await A.sync();
const c2=JSON.parse(A.ev("JSON.stringify(S.meses)"))[MES].itens["i1:cafe"];
ok(c2?.s==="ok","café segue marcado (os dois marcaram, nenhum desmarcou o outro)");
ok(A.ev("JSON.stringify(S.meses)")===B.ev("JSON.stringify(S.meses)"),"continuam iguais");

console.log("3. Menu do item: tenho em casa / não achei / desfazer");
A.click(A.item("i1:azeite").querySelector(".it-more"));
ok(A.q("#sheet").open,"abre a folha de opções");
A.click(`.acao[data-s="casa"]`);
ok(!A.q("#sheet").open,"fecha depois de escolher");
ok(A.item("i1:azeite").classList.contains("s-casa"),"azeite marcado como em casa");
ok(/Desfazer/.test(A.txt("#toast")),"toast com desfazer");
A.click(`#toast [data-act="toast"]`);
ok(!A.item("i1:azeite").classList.contains("s-casa"),"desfazer volta ao estado anterior");
A.click(A.item("i1:oleo").querySelector(".it-more")); A.click(`.acao[data-s="falta"]`);
ok(A.item("i1:oleo").classList.contains("s-falta"),"óleo como não achei");

console.log("4. Extra e finalizar compra");
A.click(`[data-act="extra"]`); A.q("#ex-n").value="Pilhas AA"; A.q("#ex-q").value="1 pacote"; A.click(`[data-act="salvarextra"]`);
const ex=A.qa(".it[data-k]").find(x=>/Pilhas AA/.test(x.textContent));
ok(!!ex,"extra aparece na lista");
await wait(300); await A.sync(); await B.sync();
ok(B.qa(".it[data-k]").some(x=>/Pilhas AA/.test(x.textContent)),"extra aparece para B");
A.click(`[data-act="finalizar"]`);
ok(/Finalizar compra/.test(A.txt("#sheet")),"folha de finalizar");
ok(/de fora/.test(A.txt("#sheet")),"mostra itens que ficaram de fora");
A.type("#valor","1.480,50");
ok(/abaixo do previsto/.test(A.txt("#valor-hint")),"dica ao digitar: "+A.txt("#valor-hint"));
A.click(`[data-act="levar"]`);
await wait(50);
const m=JSON.parse(A.ev("JSON.stringify(S.meses)"))[MES];
const ex2=Object.values(m.extras.i2||{}).map(e=>e.n);
ok(ex2.includes("Óleo")&&ex2.includes("Arroz")===false,"levou itens de fora para o dia 8 (óleo sim, arroz já pego não): "+ex2.length+" itens");
ok(!ex2.includes("Banana"),"não duplica o que já está na lista do dia 8");
A.q("#valor").value="1.480,50"; A.click(`[data-act="salvarvalor"]`);
ok(JSON.parse(A.ev("JSON.stringify(S.meses)"))[MES].notas.i1===1480.5,"valor 1.480,50 salvo como 1480.5");
ok(/Pago no caixa/.test(A.txt(".actionbar")),"barra mostra valor pago");
await wait(300); await A.sync(); await B.sync();

console.log("5. Tela do mês");
B.ir("#/"); await wait(50);
ok(/R\$\s?1\.480,50/.test(B.txt(".pricetag")),"gasto do mês para B: "+B.txt(".pricetag"));
ok(B.qa(".ida").length===4,"4 idas");
ok(/abaixo/.test(B.txt(".ida.feita")),"ida 1 concluída com comparação: "+B.txt(".ida.feita .valor"));

console.log("6. Ajustes: pessoas e valores");
B.ir("#/ajustes"); await wait(50);
B.click(`[data-act="pessoas"][data-d="1"]`);
ok(B.txt(".stepper output")==="4","4 pessoas");
ok(/Ajustar valores também/.test(B.txt("#toast")),"oferece ajustar valores");
B.click(`#toast [data-act="toast"]`);
const C=JSON.parse(B.ev("JSON.stringify(cfg().idas)"));
ok(C.i1.est===2045&&C.i2.est===220,"valores escalados 4/3: "+C.i1.est+", "+C.i2.est);
await wait(300); await B.sync(); await A.sync();
A.ir("#/ida/i1"); await wait(50); A.click(`[data-act="filtro"][data-f="todos"]`);
ok(A.txt(`.it[data-k="i1:frango"] .it-q`)==="8 kg","A vê frango 8 kg para 4 pessoas");
ok(A.txt(`.it[data-k="i1:abobrinha"] .it-q`)==="800 g","abobrinha 800 g");
ok(A.txt(`.it[data-k="i1:ovos"] .it-q`)==="80 ovos","ovos 80");
ok(A.txt(`.it[data-k="i1:sanitario"] .it-q`)==="1 kit para 3 banheiros","item fixo não muda");
ok(JSON.parse(A.ev("JSON.stringify(cfgMes(ver))")).pessoas===4,"mês atual passou para 4 pessoas");
B.type("#est-i2","250");
await wait(50);
ok(JSON.parse(B.ev("JSON.stringify(cfg().idas.i2)")).est===250,"previsto do dia 8 editado");
B.type("#nome-i3","Feira do meio");
ok(JSON.parse(B.ev("JSON.stringify(cfg().idas.i3)")).nome==="Feira do meio","nome da ida editado");

console.log("7. Editor da lista");
B.ir("#/lista"); await wait(50);
ok(B.qa(".edit-it").length===46,"46 itens na lista: "+B.qa(".edit-it").length);
B.click(`[data-act="novoitem"]`);
B.q("#ed-n").value="Granola"; B.q("#ed-s").value="Mercearia"; B.q("#ed-u").value="pacote";
const cb2=B.q(`[data-dia="i2"]`); cb2.checked=true; cb2.dispatchEvent(new B.w.Event("change",{bubbles:true}));
B.q(`[data-q="i1"]`).value="2"; B.q(`[data-q="i2"]`).value="1";
B.click(`[data-act="salvaritem"]`);
await wait(300); await B.sync(); await A.sync();
A.ir("#/ida/i2"); await wait(50);
ok(A.qa(".it[data-k]").some(x=>/Granola/.test(x.textContent)&&/1 pacote/.test(x.textContent)),"Granola aparece no dia 8 para A com 1 pacote");
const lst=JSON.parse(srv.sheets.dados.find(r=>r[0]==="config")[1]).lista;
ok(Object.keys(lst).length===47,"lista gravada na planilha com 47 itens");
B.click(B.qa(".edit-it .it-main").find(x=>/Granola/.test(x.textContent)));
B.click(`[data-act="excluiritem"]`);
ok(!B.qa(".edit-it").some(x=>/Granola/.test(x.textContent)),"excluir item");

console.log("8. Planilha");
const rows=srv.sheets.dados.filter(r=>r[0]).map(r=>r[0]);
ok(rows.includes("config")&&rows.includes("mes:"+MES),"linhas: "+rows.join(", "));
const res=srv.sheets.resumo;
ok(res&&res[0][0]==="Mês"&&res[1][0]===MES,"aba resumo gerada: "+JSON.stringify(res&&res[1]));
ok(typeof srv.props.rev==="string"&&srv.props.rev.length>6,"revisão é um código único: "+srv.props.rev);

console.log("9. Consultas baratas quando nada mudou");
const g0=srv.gets; await A.sync(); 
ok(srv.gets-g0<=2,"no máximo uma ou duas consultas: "+(srv.gets-g0));
